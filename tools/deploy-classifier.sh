#!/bin/bash
# Bundle the classification rules and PUT them into the n8n Code node.
#
#   ./tools/deploy-classifier.sh            build and deploy
#   ./tools/deploy-classifier.sh --dry-run  build only
#
# The rules in src/ are the source of truth. This makes the server run
# exactly them, so the regression suite tests the code that is actually
# classifying labels in production and the two can never drift.
set -e
cd "$(dirname "$0")/.."

ENV_FILE="../.secrets/n8n.env"     # N8N_URL and N8N_API_KEY. Outside this repo.
CONFIG_FILE=".env"                 # addresses and ids. Gitignored, see .env.example.

if [ -f "$CONFIG_FILE" ]; then set -a; . "./$CONFIG_FILE"; set +a; fi
WF_ID="${N8N_WF_ID:-}"
export HIP_API_BASE="${EXPO_PUBLIC_HIP_API_BASE:-}"
if [ -z "$WF_ID" ] || [ -z "$HIP_API_BASE" ]; then
  echo "Missing config. Copy .env.example to .env and fill in"
  echo "EXPO_PUBLIC_HIP_API_BASE and N8N_WF_ID."
  exit 1
fi
NODE_NAME="Classify lines"
OUT="${TMPDIR:-/tmp}/hip-classifier-bundle.js"

say() { printf '\n\033[1m%s\033[0m\n' "$1"; }

say "1/4  Checking the rules"
npx tsc --noEmit
./tools/test.sh > /dev/null && echo "     tests pass"

say "2/4  Bundling"
WORK=$(mktemp -d); trap 'rm -rf "$WORK"' EXIT
mkdir -p "$WORK/src" "$WORK/tools"
# Copy everything and let esbuild tree-shake: only what the two entry
# points actually reach ends up in a bundle. Listing files by hand meant a
# transitive import (dsld -> product) broke the build.
cp src/*.ts "$WORK/src/"
cp tools/classifier-entry.ts tools/match-entry.ts tools/pack-entry.ts "$WORK/tools/"
perl -pi -e "s{(from '\./[A-Za-z]+)'}{\$1.ts'}g" "$WORK/src"/*.ts

npx --yes esbuild "$WORK/tools/classifier-entry.ts" \
  --bundle --format=iife --platform=neutral --target=es2022 \
  --outfile="$WORK/bundle.js" --log-level=warning

# The packaging reader: readPack, mergePacks and the panel parse they need.
npx --yes esbuild "$WORK/tools/pack-entry.ts" \
  --bundle --format=iife --platform=neutral --target=es2022 \
  --outfile="$WORK/pack.js" --log-level=warning
{
  echo "// GENERATED by tools/deploy-classifier.sh -- do not edit here."
  echo "// Source of truth: hiptestbed/src/labelPack.ts and labelPackClassification.ts."
  cat "$WORK/pack.js"
  cat <<'PTAIL'

const body = $input.first().json.body ?? $input.first().json;
return [{ json: globalThis.hipReadPack(body) }];
PTAIL
} > "${TMPDIR:-/tmp}/hip-pack-bundle.js"
echo "     pack $(wc -c < "${TMPDIR:-/tmp}/hip-pack-bundle.js" | tr -d ' ') bytes"

# The matcher is a second, much smaller bundle: just the scoring and the
# thresholds. It is written next to the patch script, which inlines it.
npx --yes esbuild "$WORK/tools/match-entry.ts" \
  --bundle --format=iife --platform=neutral --target=es2022 \
  --outfile="tools/match-bundle.js" --log-level=warning
echo "     matcher $(wc -c < tools/match-bundle.js | tr -d ' ') bytes"

{
  echo "// GENERATED by tools/deploy-classifier.sh -- do not edit here."
  echo "// Source of truth: hiptestbed/src/labelLineClassification.ts and"
  echo "// labelPackClassification.ts. Edit there, run the tests, redeploy."
  echo "// Built $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  cat "$WORK/bundle.js"
  cat <<'TAIL'

const body = $input.first().json.body ?? $input.first().json;
return [{ json: globalThis.hipClassifyTexts(body) }];
TAIL
} > "$OUT"

echo "     $(wc -c < "$OUT" | tr -d ' ') bytes -> $OUT"
[ "$1" = "--dry-run" ] && { echo "     dry run, nothing deployed"; exit 0; }

say "3/4  Reading the workflow"
set -a; . "$ENV_FILE"; set +a
curl -fsS -H "X-N8N-API-KEY: $N8N_API_KEY" \
  "$N8N_URL/api/v1/workflows/$WF_ID" -o "$WORK/wf.json"

say "4/4  Updating the workflow"
node tools/patch-classify-workflow.mjs "$WORK/wf.json" "$OUT" "$WORK/next.json" \
  "${TMPDIR:-/tmp}/hip-pack-bundle.js"
curl -fsS -X PUT -H "X-N8N-API-KEY: $N8N_API_KEY" \
  -H 'content-type: application/json' \
  "$N8N_URL/api/v1/workflows/$WF_ID" \
  --data-binary "@$WORK/next.json" -o "$WORK/res.json"
node -e "const w=require('$WORK/res.json');console.log('     updated:',w.name,'| nodes',w.nodes.length)"

say "5/5  Parity: does the deployed node agree with the local rules?"
# Same copy-and-add-extensions dance as test.sh: Node needs explicit .ts on
# imports, Metro does not, and the app's source is written for Metro.
PWORK=$(mktemp -d)
mkdir -p "$PWORK/src" "$PWORK/tools" "$PWORK/assets"
cp src/*.ts "$PWORK/src/"; cp tools/parity.ts "$PWORK/tools/"
cp assets/sample-label.json "$PWORK/assets/"
perl -pi -e "s{(from '\./[A-Za-z]+)'}{\$1.ts'}g" "$PWORK/src"/*.ts
sleep 2   # the workflow needs a moment to re-register after a PUT
node --experimental-strip-types --no-warnings "$PWORK/tools/parity.ts"
rm -rf "$PWORK"
